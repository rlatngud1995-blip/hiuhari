/* ============================================
   지역 + 시술 검색어 생성

   예:
   천안 여자 염색 잘하는 곳
   천안 염색맛집
   청당동 신부염색
============================================ */

export function getRegionalKeywords(
  region: string,
  service: string
): string[] {
  const regionName = REGION_NAMES[region];
  const config = SEO_KEYWORDS[service];

  if (!regionName || !config) return [];

  return Array.from(
    new Set([
      `${regionName} ${config.main}`,
      ...config.variations.map(
        (keyword) => `${regionName} ${keyword}`
      ),
      `${regionName} ${config.main} 하이유헤어`,
    ])
  );
}

/* ============================================
   제목과 설명

   다른 동네에는 별도 매장이 없음을 유지
============================================ */

export function getRegionalSeo(
  region: string,
  service: string
) {
  const regionName = REGION_NAMES[region];
  const config = SEO_KEYWORDS[service];

  if (!regionName || !config) return null;

  const isNearby =
    region !== "cheonan" &&
    region !== "cheongdang";

  const title = isNearby
    ? `${regionName} ${config.main} 안내 | 하이유헤어 청당점`
    : `${regionName} ${config.main} | 하이유헤어 청당점`;

  const description = isNearby
    ? `${regionName}에서 ${config.main}을 알아보시나요? ${config.description} 실제 매장은 천안 청당동 하이유헤어 청당점입니다.`
    : `${regionName} ${config.description} 하이유헤어 청당점 이해린 디자이너의 스타일과 예약 정보를 확인하세요.`;

  return {
    title,
    description,
    keywords: getRegionalKeywords(region, service),
    guide: config.searchGuide,
  };
}
